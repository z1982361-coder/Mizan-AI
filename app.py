def analyze(situation):
    text_in = (situation or "").strip()

    # معالجة المدخلات الفارغة أو غير المناسبة
    if not text_in:
        yield "### ✍️ لم تكتب أي موقف\nمن فضلك اكتب وصف الموقف في المربع أولًا، أو اختر أحد الأمثلة."
        return
    if len(text_in) < 15:
        yield "### ✍️ الوصف قصير جدًا\nاكتب الموقف بتفصيل أكبر (جملتان على الأقل) ليكون التحليل دقيقًا."
        return
    if len(text_in) > 3000:
        yield "### ✂️ النص طويل جدًا\nاختصر وصف الموقف إلى أقل من 3000 حرف."
        return
    if client is None:
        yield STARTUP_ERROR or "### ⚠️ التطبيق غير متصل بـ Gemini. أعد تشغيل الخلية."
        return

    yield LOADING

    prompt = (
        "وصف الموقف من المستخدم:\n"
        f"<situation>\n{text_in}\n</situation>\n\n"
        "حلّل هذا الموقف وفق التنسيق والقواعد المطلوبة."
    )

    for attempt in range(3):
        try:
            response = client.models.generate_content(
                model=MODEL_NAME,
                contents=prompt,
                config={"system_instruction": SYSTEM_INSTRUCTION},
            )
            answer = (response.text or "").strip()
            if not answer:
                yield ("### 🚫 لم يصدر رد من النموذج\n"
                       "ربما تم حجب الرد لأسباب تتعلق بالسلامة. أعد صياغة الموقف بعبارات أوضح وحاول مجددًا.")
                return
            yield answer + DISCLAIMER
            return
        except errors.APIError as e:
            code = getattr(e, "code", None)
            if code in (429, 500, 502, 503, 504) and attempt < 2:
                time.sleep(3 * (attempt + 1))   # إعادة محاولة تلقائية
                continue
            yield friendly_api_error(e)
            return
        except Exception:
            yield ("### 🌐 تعذّر الاتصال بالخدمة\n"
                   "تحقق من اتصال الإنترنت ثم حاول مرة أخرى.")
            return


