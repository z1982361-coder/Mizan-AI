def friendly_api_error(e):
    """يحوّل أخطاء Gemini إلى رسائل عربية واضحة (دون عرض أي أسرار)."""
    code = getattr(e, "code", None)
    low = str(e).lower()
    if code in (401, 403) or (code == 400 and "api key" in low):
        return ("### 🔑 مشكلة في مفتاح API\n"
                "المفتاح غير صالح أو لا يملك الصلاحية. تأكد من نسخه كاملًا من Google AI Studio، "
                "ومن حفظه في Colab Secrets باسم `GEMINI_API_KEY` مع تفعيل «Notebook access».")
    if code == 429:
        return ("### ⏳ تم تجاوز حد الاستخدام\n"
                "وصلتَ إلى الحد المسموح للطلبات حاليًا. انتظر دقيقة ثم حاول مرة أخرى.")
    if code in (500, 502, 503, 504):
        return ("### 🛠️ الخدمة مشغولة مؤقتًا\n"
                "خوادم Gemini تواجه ضغطًا الآن. أعد المحاولة بعد قليل.")
    if code == 404:
        return ("### 🔎 النموذج غير متاح\n"
                "النموذج المطلوب غير متاح لمفتاحك حاليًا. أعد تشغيل الخلية ليتم اختيار نموذج آخر.")
    return (f"### ⚠️ حدث خطأ غير متوقع من خدمة Gemini (الرمز: {code})\n"
            "حاول مرة أخرى، وإن تكرر الخطأ فأعد تشغيل الخلية.")


def connect_to_gemini(api_key):
    """يرجع (client, model_name, error_message)."""
    try:
        client = genai.Client(api_key=api_key)
    except Exception:
        return None, None, "### ⚠️ تعذّر تهيئة الاتصال بـ Gemini. تأكد من المفتاح ثم أعد التشغيل."

    last_error = None
    for model in CANDIDATE_MODELS:
        try:
            client.models.generate_content(
                model=model, contents="أجب بكلمة واحدة فقط: جاهز"
            )
            return client, model, None
        except errors.APIError as e:
            code = getattr(e, "code", None)
            low = str(e).lower()
            if code == 404:                     # النموذج غير موجود -> جرّب التالي
                last_error = e
                continue
            if code in (401, 403) or (code == 400 and "api key" in low):
                return None, None, friendly_api_error(e)   # مشكلة مفتاح
            if code in (429, 500, 502, 503, 504):
                return client, model, None      # النموذج موجود لكن مشغول مؤقتًا
            last_error = e
            continue
        except Exception:
            return None, None, ("### 🌐 تعذّر الاتصال بالإنترنت أو بخدمة Gemini\n"
                                "تأكد من اتصال Colab بالإنترنت ثم أعد التشغيل.")
    msg = "### 🔎 لم أجد نموذج Gemini متاحًا لمفتاحك حاليًا.\nحاول لاحقًا أو أنشئ مفتاحًا جديدًا."
    if last_error is not None:
        msg += f"\n\n(الرمز: {getattr(last_error, 'code', '؟')})"
    return None, None, msg


